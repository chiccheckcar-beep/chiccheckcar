# python3 tools/gen_legal.py site
# Builds one standalone page per legal document from the legal windows in index.html (single source of the texts):
#   privacy.html, privacy-settings.html, terms.html, accessibility.html
# index.html links (footer, side menu, gate consent) open these pages. Re-run after editing a legal text in index.html.
import re, sys, html as H

site = sys.argv[1]
src = open(f'{site}/index.html', encoding='utf-8').read()

PAGES = [  # (window id in index.html, page file, short label for the nav)
    ('privacy', 'privacy.html', 'מדיניות פרטיות'),
    ('settings', 'privacy-settings.html', 'הגדרות פרטיות'),
    ('service', 'terms.html', 'תנאי שירות'),
    ('accessibility', 'accessibility.html', 'הצהרת נגישות'),
]

def block(name):
    m = re.search(r'<div class="legal" id="legal-' + name + r'".*?<h2[^>]*>(.*?)</h2>.*?<div class="legal-body">(.*?)\n </div></div>\n</div>', src, re.S)
    if not m: sys.exit('legal window not found: ' + name)
    return m.group(1).strip(), m.group(2)

SETTINGS_JS = r'''<script>
(function(){
  const KEYS = __KEYS__;
  const store = l => { try { return l ? localStorage : sessionStorage; } catch(e) { return null; } };
  const get = (k, l) => { try { return store(l).getItem(k); } catch(e) { return null; } };
  function render(){
    const box = document.getElementById('setList'); box.textContent = '';
    for (const [k,label,l] of KEYS){
      const row = document.createElement('div'); row.className = 'set-row';
      const t = document.createElement('div'); const b = document.createElement('b'); b.textContent = label;
      const s = document.createElement('span'); s.textContent = k + (l ? ' · שמירה לבחירתכם · עד שתמחקו' : ' · הכרחי · עד סגירת הלשונית');
      t.append(b, s);
      const tag = document.createElement('span'); tag.className = 'set-tag'; tag.textContent = get(k, l) !== null ? 'שמור' : 'לא שמור';
      row.append(t, tag); box.append(row);
    }
  }
  document.getElementById('setClear').addEventListener('click', () => {
    for (const [k,,l] of KEYS){ try { store(l).removeItem(k); } catch(e) {} }
    render();
    document.getElementById('setMsg').textContent = 'המידע נמחק מהדפדפן. בכניסה הבאה לאתר יוצג שוב מסך הכניסה.';
  });
  render();
})();
</script>'''

keys = re.search(r'const KEYS = (\[.*?\]);\n', src).group(1)

