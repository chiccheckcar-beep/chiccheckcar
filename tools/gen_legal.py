for name, file, label in PAGES:
    title, body = block(name)
    cur = ' aria-current="page"'
    nav = ''.join(f'<a href="{f}"{cur if f == file else ""}>{l}</a>' for _, f, l in PAGES)
    page = TPL.replace('__TITLE__', title).replace('__BODY__', body).replace('__NAV__', nav)
    page = page.replace('__JS__', SETTINGS_JS.replace('__KEYS__', keys) if name == 'settings' else '')
    open(f'{site}/{file}', 'w', encoding='utf-8').write(page)
    print(file, len(page))
